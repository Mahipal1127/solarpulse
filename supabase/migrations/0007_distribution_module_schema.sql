-- ---------------------------------------------------------------------------
-- Document numbering
--
-- A counter row per (org, type, year). `on conflict do update ... returning`
-- takes a row lock, so two concurrent creates serialize and cannot be handed the
-- same number — which is what the count(*) + 1 approach would do under
-- concurrency. The unique constraints above are the second line of defence.
-- ---------------------------------------------------------------------------

create table document_counters (
  organization_id uuid not null references organizations(id) on delete cascade,
  -- 'PO' | 'DSP'
  doc_type        text not null,
  year            int  not null,
  last_value      int  not null default 0,
  primary key (organization_id, doc_type, year)
);

create or replace function next_document_number(p_org_id uuid, p_doc_type text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_year int := extract(year from now())::int;
  v_seq  int;
begin
  insert into document_counters (organization_id, doc_type, year, last_value)
  values (p_org_id, p_doc_type, v_year, 1)
  on conflict (organization_id, doc_type, year)
  do update set last_value = document_counters.last_value + 1
  returning last_value into v_seq;

  return p_doc_type || '-' || v_year::text || '-' || lpad(v_seq::text, 4, '0');
end;
$$;

-- ---------------------------------------------------------------------------
-- total_amount recompute
--
-- Lives in the database, not application code, so the denormalized total can
-- never drift from the line items — whatever path writes an item, this runs.
-- ---------------------------------------------------------------------------

create or replace function recompute_po_total()
returns trigger
language plpgsql
as $$
declare
  v_po_id uuid := coalesce(new.purchase_order_id, old.purchase_order_id);
begin
  update purchase_orders
     set total_amount = coalesce(
           (select sum(line_total) from purchase_order_items
             where purchase_order_id = v_po_id), 0)
   where id = v_po_id;

  return null;
end;
$$;

-- after-trigger on all three verbs: an edit that deletes a line has to lower the
-- total just as much as one that adds a line raises it.
create trigger recompute_po_total_on_items
  after insert or update or delete on purchase_order_items
  for each row execute function recompute_po_total();

