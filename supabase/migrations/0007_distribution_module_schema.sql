create table purchase_orders (
  id                     uuid primary key default gen_random_uuid(),
  organization_id        uuid not null references organizations(id) on delete cascade,
  -- human-readable, e.g. 'PO-2026-0001'. Generated by next_document_number()
  -- below, never by the client.
  po_number              text not null,
  vendor_id              uuid not null references vendors(id),
  status                 purchase_order_status not null default 'draft',
  expected_delivery_date date,
  -- Denormalized for fast list display. Maintained solely by the
  -- recompute_po_total() trigger on purchase_order_items — application code must
  -- never write this column, or it will drift from the line items.
  total_amount           numeric(14, 2) not null default 0,
  created_by             uuid not null references users(id),
  -- Finance approval, per the blueprint's workflow: Finance Approval precedes
  -- Distribution dispatch.
