  approved_at            timestamptz,
  notes                  text,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  -- Backstop behind next_document_number(): even if two concurrent creates ever
  -- raced past the counter, the second would fail loudly rather than duplicate.
  unique (organization_id, po_number)
);

