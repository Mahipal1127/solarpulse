-- ---------------------------------------------------------------------------
-- Membership helpers
--
-- security definer + fixed search_path, matching auth_is_ceo() in 0001 and
-- auth_is_tender_member() in 0003, so the policies below can read
-- users/departments without recursing through their own RLS.
-- ---------------------------------------------------------------------------

create or replace function auth_is_distribution_member()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from users u
    join departments d on d.id = u.department_id
    where u.id = auth.uid() and u.is_active and d.slug = 'distribution'
  );
$$;

-- Finance's only role in this module: approving purchase orders. Accounts is a
-- child department of Finance in the 0002 seed, so it is included — an Accounts
-- user is Finance for approval purposes.
create or replace function auth_is_finance_member()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from users u
    join departments d on d.id = u.department_id
    left join departments parent on parent.id = d.parent_department_id
    where u.id = auth.uid() and u.is_active
      and (d.slug in ('finance', 'accounts') or parent.slug = 'finance')
  );
$$;

create or replace function auth_is_sales_member_dist()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from users u
    join departments d on d.id = u.department_id
    where u.id = auth.uid() and u.is_active and d.slug = 'sales'
  );
$$;

-- ---------------------------------------------------------------------------
-- Finance approval authority
--
-- A with-check expression only sees the proposed row, so it cannot tell an
-- approval apart from a PO that was already approved. This trigger can: it
-- compares OLD.status to NEW.status and refuses the transition into 'approved'
-- unless the caller is Finance or the CEO.
--
-- It also stamps approved_by/approved_at rather than trusting the caller, and
-- clears them if a PO is ever pushed back to a pre-approval state, so those
-- columns cannot claim an approval that did not happen.
-- ---------------------------------------------------------------------------

create or replace function enforce_po_approval_authority()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'approved' and old.status <> 'approved' then
    if not (auth_is_finance_member() or auth_is_ceo()) then
      raise exception 'Only Finance or the CEO can approve a purchase order'
        using errcode = 'check_violation';
    end if;

    new.approved_by := coalesce(auth.uid(), new.approved_by);
    new.approved_at := now();
  end if;

  -- Rolling back to draft or re-review drops the approval stamp with it.
  if new.status in ('draft', 'pending_finance_approval') then
    new.approved_by := null;
    new.approved_at := null;
  end if;

  return new;
end;
$$;

create trigger enforce_po_approval_authority_trg
  before update on purchase_orders
  for each row execute function enforce_po_approval_authority();

