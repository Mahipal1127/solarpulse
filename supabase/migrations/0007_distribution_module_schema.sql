-- Solar Pulse OS — Distribution Module
-- Migration 0007: vendors, purchase orders, dispatches, allocations, returns
--
-- Builds on 0001/0002/0005. Reuses organizations / departments / roles / users /
-- audit_logs / leads and the set_updated_at() trigger function, plus the
-- auth_is_ceo() / auth_org_id() helpers — none of those are redefined here.
--
-- Security model is TWO tiers, not three: material movement is a shared
-- department operation, so every Distribution member sees every PO, dispatch,
-- allocation, and return. There is deliberately no per-employee ownership tier
-- like Sales has — a dispatch is not personal pipeline data.
--
-- The one place this module's permissions are not a flat two-tier pattern is the
-- Finance approval gate on purchase orders. Distribution may prepare a PO and
-- act on it once approved, but may not approve it themselves. That is enforced
-- three ways, deliberately redundant:
--   1. the service layer's transition table (clear 400s),
--   2. the narrowed Distribution update policy below,
--   3. enforce_po_approval_authority(), a trigger that can compare OLD.status to
--      NEW.status — something a with-check expression cannot do.

