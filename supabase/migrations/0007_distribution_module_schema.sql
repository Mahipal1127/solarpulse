-- ---------------------------------------------------------------------------
-- create_purchase_order(): PO + line items in one statement
--
-- One call rather than an insert followed by N item inserts: a client-side
-- sequence could fail partway and leave a PO with half its lines, and its
-- total_amount would then be a real number that happens to be wrong.
--
-- Not security definer — it runs as the caller, so every write inside still
-- passes RLS. The numbering call inside it is security definer because
-- document_counters denies everyone.
-- ---------------------------------------------------------------------------

create or replace function create_purchase_order(
  p_vendor_id     uuid,
  p_items         jsonb,
  p_expected_date date default null,
  p_notes         text default null,
  p_submit        boolean default false
)
returns uuid
language plpgsql
as $$
declare
  v_org_id uuid := auth_org_id();
  v_po_id  uuid;
  v_item   jsonb;
  v_count  int  := 0;
begin
  if v_org_id is null then
    raise exception 'No organization for the current user';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'A purchase order needs at least one line item';
  end if;

  -- RLS decides visibility: a vendor outside the caller's org yields no row.
  if not exists (
    select 1 from vendors v
    where v.id = p_vendor_id and v.organization_id = v_org_id and v.is_active
  ) then
    raise exception 'Vendor not found or inactive';
  end if;

  insert into purchase_orders (
    organization_id, po_number, vendor_id, status,
    expected_delivery_date, created_by, notes
  )
  values (
    v_org_id,
    next_document_number(v_org_id, 'PO'),
    p_vendor_id,
    case when p_submit then 'pending_finance_approval'::purchase_order_status
         else 'draft'::purchase_order_status end,
    p_expected_date,
    auth.uid(),
    p_notes
  )
  returning id into v_po_id;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    insert into purchase_order_items (
      purchase_order_id, item_name, category, quantity, unit, unit_price
    )
    values (
      v_po_id,
      v_item->>'item_name',
      nullif(v_item->>'category', ''),
      (v_item->>'quantity')::numeric,
      coalesce(nullif(v_item->>'unit', ''), 'nos'),
      (v_item->>'unit_price')::numeric
    );
    v_count := v_count + 1;
  end loop;

  -- total_amount is now set by the recompute trigger, not by this function.
  return v_po_id;
end;
$$;

revoke execute on function create_purchase_order(uuid, jsonb, date, text, boolean) from anon;

-- ---------------------------------------------------------------------------
-- replace_purchase_order_items(): swap a draft PO's whole line-item set
--
-- Editing lines means deleting the old ones and inserting the new. Split across
-- two client calls, a failure between them leaves the PO with no lines at all —
-- and total_amount recomputed to 0, which is self-consistent but wrong. One
-- statement makes the swap all-or-nothing.
--
-- The draft check is repeated here rather than trusted from the caller: once
-- Finance has been asked to approve an amount, the lines behind that amount must
-- not move under them.
-- ---------------------------------------------------------------------------

create or replace function replace_purchase_order_items(p_po_id uuid, p_items jsonb)
returns void
language plpgsql
as $$
declare
  v_status purchase_order_status;
  v_item   jsonb;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'A purchase order needs at least one line item';
  end if;

  -- RLS applies: a PO the caller cannot see yields no row and the same error as
  -- one that does not exist.
  select status into v_status from purchase_orders where id = p_po_id for update;
  if not found then
    raise exception 'Purchase order not found';
  end if;

  if v_status <> 'draft' then
    raise exception 'Line items can only be edited while the purchase order is a draft';
  end if;

  delete from purchase_order_items where purchase_order_id = p_po_id;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    insert into purchase_order_items (
      purchase_order_id, item_name, category, quantity, unit, unit_price
    )
    values (
      p_po_id,
      v_item->>'item_name',
      nullif(v_item->>'category', ''),
      (v_item->>'quantity')::numeric,
      coalesce(nullif(v_item->>'unit', ''), 'nos'),
      (v_item->>'unit_price')::numeric
    );
  end loop;
end;
$$;

revoke execute on function replace_purchase_order_items(uuid, jsonb) from anon;

-- ---------------------------------------------------------------------------
-- Releasing allocations when a dispatch is cancelled
--
-- create_dispatch_from_allocations() moves allocations to 'dispatched' and points
-- them at the new dispatch. If that dispatch is then cancelled, those rows would
-- otherwise sit at 'dispatched' forever, pointing at something that never went
-- out — and since ALLOCATION_TRANSITIONS has no edge back to 'allocated', the
-- material would be permanently un-dispatchable.
--
-- Handled in the database for the same reason as total_amount: the invariant then
-- holds no matter which path cancels the dispatch.
-- ---------------------------------------------------------------------------

create or replace function release_allocations_on_dispatch_cancel()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'cancelled' and old.status <> 'cancelled' then
    -- Scoped by linked_dispatch_id, so this only ever touches allocations that
    -- pointed at this dispatch — already org-bounded by the dispatch row itself.
    -- Only 'dispatched' rows are released: one already marked 'returned' has a
    -- return record behind it and is not this trigger's business.
    update material_allocations
       set status = 'allocated', linked_dispatch_id = null
     where linked_dispatch_id = new.id
       and status = 'dispatched';
  end if;

  return null;
end;
$$;

create trigger release_allocations_on_dispatch_cancel_trg
  after update on material_dispatches
  for each row execute function release_allocations_on_dispatch_cancel();

-- ---------------------------------------------------------------------------
-- create_dispatch_from_allocations(): dispatch + items + allocation updates
--
-- The atomicity requirement in this module. Creating a dispatch out of planned
-- allocations touches three tables, and a partial failure would leave either a
-- dispatch whose allocations still read 'allocated' (so the same material gets
-- sent twice) or allocations marked 'dispatched' pointing at nothing. One
-- statement makes both impossible.
--
-- p_allocation_ids may be empty, which is the ad-hoc dispatch case: items come
-- straight from p_items instead.
-- ---------------------------------------------------------------------------

create or replace function create_dispatch_from_allocations(
  p_lead_id         uuid default null,
  p_allocation_ids  uuid[] default '{}',
  p_items           jsonb default '[]',
  p_vehicle_details text default null,
  p_driver_contact  text default null,
  p_notes           text default null
)
returns uuid
language plpgsql
as $$
declare
  v_org_id      uuid := auth_org_id();
  v_dispatch_id uuid;
  v_item        jsonb;
  v_alloc       record;
  v_item_count  int := 0;
begin
  if v_org_id is null then
    raise exception 'No organization for the current user';
  end if;

  insert into material_dispatches (
    organization_id, dispatch_number, lead_id, dispatched_by,
    vehicle_details, driver_contact, status, delivery_notes
  )
  values (
    v_org_id,
    next_document_number(v_org_id, 'DSP'),
    p_lead_id,
    auth.uid(),
    p_vehicle_details,
    p_driver_contact,
    'preparing',
    p_notes
  )
  returning id into v_dispatch_id;

  -- Allocation-sourced items. `for update` locks each allocation row, so two
  -- dispatches cannot claim the same allocation concurrently.
  if array_length(p_allocation_ids, 1) > 0 then
    for v_alloc in
      select * from material_allocations
      where id = any(p_allocation_ids)
        and organization_id = v_org_id
      for update
    loop
      if v_alloc.status <> 'allocated' then
        raise exception 'Allocation for % is already %', v_alloc.item_name, v_alloc.status;
      end if;

      -- A dispatch drawn from allocations must go to the project they were
      -- earmarked for, or the plan record stops meaning anything.
      if p_lead_id is not null and v_alloc.lead_id <> p_lead_id then
        raise exception 'Allocation for % belongs to a different project', v_alloc.item_name;
      end if;

      insert into material_dispatch_items (dispatch_id, item_name, category, quantity, unit)
      values (v_dispatch_id, v_alloc.item_name, v_alloc.category, v_alloc.quantity, v_alloc.unit);

      update material_allocations
         set status = 'dispatched', linked_dispatch_id = v_dispatch_id
       where id = v_alloc.id;

      v_item_count := v_item_count + 1;
    end loop;

    -- Fewer rows touched than ids passed means at least one was invisible to
    -- this caller or outside their org. Fail rather than silently short-ship.
    if v_item_count <> array_length(p_allocation_ids, 1) then
      raise exception 'One or more allocations could not be found';
    end if;
  end if;

  -- Ad-hoc items, added alongside or instead of allocations.
  if p_items is not null and jsonb_typeof(p_items) = 'array' then
    for v_item in select * from jsonb_array_elements(p_items)
    loop
      insert into material_dispatch_items (dispatch_id, item_name, category, quantity, unit)
      values (
        v_dispatch_id,
        v_item->>'item_name',
        nullif(v_item->>'category', ''),
        (v_item->>'quantity')::numeric,
        coalesce(nullif(v_item->>'unit', ''), 'nos')
      );
      v_item_count := v_item_count + 1;
    end loop;
  end if;

  if v_item_count = 0 then
    raise exception 'A dispatch needs at least one item';
  end if;

  return v_dispatch_id;
end;
$$;

revoke execute on function create_dispatch_from_allocations(uuid, uuid[], jsonb, text, text, text) from anon;

-- ---------------------------------------------------------------------------
-- Seed: Distribution Manager role + module permissions
--
-- 0002 seeds only CEO and '<Department> Executive'. The Distribution module has
-- no manager-only behaviour of its own — the tiers here are CEO and department —
-- but the role is seeded so the '<Department> Manager' convention that
-- isDepartmentManager() and auth_is_department_manager() rely on holds for
-- Distribution too, and so CEO-assigned department tasks have someone to
-- delegate them.
-- ---------------------------------------------------------------------------

do $$
declare
  org_id       uuid;
  dist_dept_id uuid;
  mgr_role_id  uuid;
  exec_role_id uuid;
begin
  select id into org_id from organizations where name = 'Solar Pulse';
  if org_id is null then return; end if;

  select id into dist_dept_id
    from departments
   where organization_id = org_id and slug = 'distribution';
  if dist_dept_id is null then return; end if;

  select id into mgr_role_id
    from roles
   where organization_id = org_id and name = 'Distribution Manager';

  if mgr_role_id is null then
    insert into roles (organization_id, department_id, name)
    values (org_id, dist_dept_id, 'Distribution Manager')
    returning id into mgr_role_id;
  end if;

  insert into permissions (role_id, module, can_view, can_create, can_edit, can_delete, can_approve, can_export)
  select mgr_role_id, m, true, true, true, false, false, true
  from unnest(array['tasks','approvals','departments','vendors','purchase_orders','dispatches','allocations','returns']) as m
  on conflict (role_id, module) do nothing;

  select id into exec_role_id
    from roles
   where organization_id = org_id and name = 'Distribution Executive';

  if exec_role_id is not null then
    insert into permissions (role_id, module, can_view, can_create, can_edit, can_delete, can_approve, can_export)
    select exec_role_id, m, true, true, true, false, false, false
    from unnest(array['vendors','purchase_orders','dispatches','allocations','returns']) as m
    on conflict (role_id, module) do nothing;
  end if;
end;
$$;
